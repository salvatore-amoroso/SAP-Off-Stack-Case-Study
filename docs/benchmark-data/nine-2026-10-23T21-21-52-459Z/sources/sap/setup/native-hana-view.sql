-- Run as SAPA4H in tenant HDB. This view exposes only the synthetic lab data.
-- The schema must first be created with OWNED BY SAPA4H.
CREATE VIEW "ZBL_BENCH_SQL"."ORDER_POSITIONS_001" AS
SELECT RTRIM(P."ORDER_ID") AS "ORDERID",
       RTRIM(P."POSITION_NUMBER") AS "POSITIONNUMBER",
       RTRIM(H."CUSTOMER_ID") AS "CUSTOMERID",
       SUBSTRING(H."ORDER_DATE", 1, 4) || '-' ||
         SUBSTRING(H."ORDER_DATE", 5, 2) || '-' ||
         SUBSTRING(H."ORDER_DATE", 7, 2) AS "ORDERDATE",
       RTRIM(P."MATERIAL_ID") AS "MATERIALID",
       CAST(P."QUANTITY" AS NVARCHAR(32)) AS "QUANTITY",
       RTRIM(P."UNIT") AS "UNIT",
       CAST(P."NET_AMOUNT" AS NVARCHAR(32)) AS "NETAMOUNT",
       RTRIM(P."CURRENCY") AS "CURRENCY"
FROM "SAPA4H"."ZBL_ORD_POS" AS P
INNER JOIN "SAPA4H"."ZBL_ORD_HDR" AS H
  ON P."CLIENT" = H."CLIENT" AND P."ORDER_ID" = H."ORDER_ID"
WHERE P."CLIENT" = '001';
